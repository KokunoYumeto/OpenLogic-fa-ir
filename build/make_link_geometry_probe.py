"""Generate one guarded-run regression driver; never launches TeX.

Run only after the owner confirms no source inputs are frozen by a live build.
The generated file is a probe, not a reader source translation or release PDF.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
FIXTURE=ROOT/'build/probes/link-geometry/link-geometry-fixture.tex'
PATCH=ROOT/'build/probes/link-geometry/link-geometry-intervention.tex'
OUTPUT=ROOT/'source/locale/fa-IR/standalone-probe-bidi-links.tex'


def sha(data):return hashlib.sha256(data).hexdigest()


def generate():
    text=FIXTURE.read_text(encoding='utf-8')
    preamble,body=text.split('\\begin{document}',1)
    examples,targets=body.split('\\chapter*{مقصدهای آزمون}',1)
    # Start each case from original macro definitions: local installation must
    # not accumulate wrappers. Destinations/bibliography are shared and unique.
    cases=[]
    for mode,name in [(0,'BASELINE'),(1,'NATIVE-ATOMIC'),(2,'ISOLATED-ATOMIC'),(3,'ISOLATED-ATOMIC-RAW-URL-LTR')]:
        cases.append('\\begingroup\n'+f'\\OLLinkGeometryInstall{{{mode}}}\n'+
            f'\\typeout{{OL-LINK-GEOMETRY-CASE={name}}}\n'+examples+'\\endgroup\n')
    return ('% Generated by build/make_link_geometry_probe.py; PROBE ONLY.\n'+preamble+
        '\\begin{document}\n'+''.join(cases)+'\\chapter*{مقصدهای آزمون}'+targets).encode('utf-8')


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--check',action='store_true')
    p.add_argument('--output',type=Path,default=OUTPUT)
    a=p.parse_args()
    data=generate()
    if a.check:
        if not a.output.is_file() or a.output.read_bytes()!=data:raise SystemExit('Probe does not match generator')
    else:
        if a.output.exists() and a.output.read_bytes()!=data:
            raise SystemExit('Refusing to replace a different existing probe; review and repair explicitly')
        a.output.write_bytes(data)
    print(json.dumps({'output':str(a.output.resolve()),'sha256':sha(data),'bytes':len(data),
        'fixture_sha256':sha(FIXTURE.read_bytes()),'intervention_sha256':sha(PATCH.read_bytes()),
        'cases':4,'tex_launched':False,'status':'GENERATED_NOT_COMPILED'},indent=2))


if __name__=='__main__':main()
