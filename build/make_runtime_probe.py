"""Create a one-pass diagnostic using current preamble and fixed historic BBL."""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
LOCALE = ROOT / 'source/locale/fa-IR'
driver = LOCALE / 'open-logic-standalone-fa-IR.tex'
bbl = ROOT / 'tmp/pdfs/standalone/20260904T160648332Z-05caf6e0aaa8475abd7899c4ee8744e1/primary/open-logic-standalone-fa-IR.bbl'
assert hashlib.sha256(bbl.read_bytes()).hexdigest() == '9e546e03a82d6d0ec2712d385e935a99b6f8c1b9ce9680252ba67203d8689609'
source = driver.read_text(encoding='utf-8')
preamble = source.split(r'\begin{document}', 1)[0]
fixture = r'''
\olgreekformulas
\noindent فرمول‌های زیر آزمونِ رفتارِ نمادها هستند.
!!{formula} و !!a{formula} و !!^a{formula} و !!{element}.
نشانهٔ تعجب در متن ! و فاکتوریل در ریاضی $5\mathexclaim=120$ و $\fact{5}=120$.
وجودِ یگانه: $\lexists![x][P(x)]$.
\[
!A \land !B \lif !C
\]
\begin{align*}
!A \lif !B & \quad !C \land !D \\
!G \lor !H & \quad !A \lif (!B \land !C)
\end{align*}
\begin{multline*}
!A(x) \land !B(y) \land {}\\
!C(z) \land !D(w).
\end{multline*}
\begin{eqnarray*}
!A&=&!B\\
!C&=&!D
\end{eqnarray*}
\begin{gather*}
!G\land !H\\
!A_{g_{k-1}}(x)\lif !A^N
\end{gather*}
\[\begin{aligned}!A&=!B\\!C&=!D\end{aligned}\]
\[\begin{array}{cc}!A&!B\\!C&!D\end{array}\]
\begin{equation}!A\quad\text{در متنِ درونِ فرمول $!B$}\tag{آزمون $!C$}\end{equation}
\begin{tabular}{cc}
$!A$ & $!B$\\
$!C$ & $!D$
\end{tabular}
\par
\ollatinformulas
\begin{align*}!A&=!B\end{align*}
\olalphagreekformulas
\begin{align*}!A&=!B\end{align*}
\olgreekformulas
'''
raw = bbl.read_text(encoding='utf-8')
parts = re.split(r'(?=\\bibitem\[)', raw)
selected = ['Boolos2000','Hume1740','Montague1961','WhiteheadRussell1910']
entries = []
for key in selected:
    hits = [p for p in parts[1:] if re.search(r'\]\{' + re.escape(key) + r'\}', p)]
    assert len(hits) == 1, key
    entries.append(hits[0].split(r'\end{thebibliography}', 1)[0])
sample = parts[0].replace('{131}', '{4}', 1) + ''.join(entries) + '\\end{thebibliography}\n'
bib_wrapper = source[source.index(r'\begingroup'+'\n'+r'\begin{otherlanguage}{english}') : source.index(r'\end{otherlanguage}'+'\n'+r'\endgroup')+len(r'\end{otherlanguage}'+'\n'+r'\endgroup')]
assert r'\bibliography{standalone-bibliography}' in bib_wrapper
bib_wrapper = bib_wrapper.replace(r'\bibliography{standalone-bibliography}', sample)
output = (preamble + r'\begin{document}' + '\n' +
          r'\section*{آزمون پیش از اصلاح}' + fixture + r'\clearpage' + '\n' +
          r'\input{standalone/runtime-fixes.tex}' + '\n' +
          r'\section*{آزمون پس از اصلاح}' + fixture + r'\clearpage' + '\n' +
          bib_wrapper + '\n' + r'\end{document}' + '\n').encode('utf-8')
target = LOCALE / 'standalone-probe-runtime.tex'
receipt = {'schema':'standalone-runtime-probe-fixture-v1',
           'driver_sha256':hashlib.sha256(driver.read_bytes()).hexdigest(),
           'bbl_sha256':hashlib.sha256(bbl.read_bytes()).hexdigest(),
           'bibliography_keys':selected, 'output':target.relative_to(ROOT).as_posix(),
           'sha256':hashlib.sha256(output).hexdigest(), 'bytes':len(output),
           'tex_run':False, 'not_full_reader':True}
receipt_path = ROOT / 'evidence/RUNTIME_PROBE_FIXTURE.json'
receipt_data = (json.dumps(receipt, indent=2) + '\n').encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify deterministic generated bytes without writing')
    args = parser.parse_args()
    if args.check:
        if not target.is_file() or target.read_bytes() != output:
            raise SystemExit('Runtime probe does not match generator')
        if not receipt_path.is_file() or receipt_path.read_bytes() != receipt_data:
            raise SystemExit('Runtime probe fixture receipt does not match generator')
    else:
        target.write_bytes(output)
        receipt_path.write_bytes(receipt_data)
    print(json.dumps(receipt))


if __name__ == '__main__':
    main()
